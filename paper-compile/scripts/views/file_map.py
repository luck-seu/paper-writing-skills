"""The file-map machine view: the paper as an assembly of files.

Part of the paper-compile state compiler (see scripts/README.md).
One row per .tex file, in assembly order: its role (macros vs
prose, classified by content in macromap -- no file name is
hardcoded), whether paper.tex \\inputs it, and what is inside
(headings for prose, a definition count for macro sources). Files
not mentioned by paper.tex append after, marked
not-yet-included -- in-progress work is exactly the writing state
worth seeing. This is the artifact other skills reference
(paper-scaffold's section-file lookup starts here).
"""

from __future__ import annotations

import os
import re

from core import copilot, macromap

_HEADING_RE = re.compile(r"\\(section|subsection|subsubsection)\*?\{")
_LABEL_RE = re.compile(r"\\label\{([^{}]*)\}")


def scan_headings(path: str, swallow: frozenset[str]) -> list[tuple[str, str]]:
    """Headings as (title, label) in file order.

    A heading's label is the first \\label between it and the next
    heading ('' when none). Titles are raw -- macros stay
    unexpanded, whitespace flattens to single spaces. Content is
    read through macromap.read_content, so \\eat-style removed
    content (an eaten \\section included) never reaches the scan.
    """
    text = macromap.read_content(path, swallow)
    entries: list[tuple[str, str]] = []
    pos = 0
    while True:
        hit = _HEADING_RE.search(text, pos)
        if hit is None:
            break
        title, _rest = macromap.take_braced(text[hit.end() - 1:])
        nxt = _HEADING_RE.search(text, hit.end())
        stop = nxt.start() if nxt else len(text)
        label_hit = _LABEL_RE.search(text, hit.end(), stop)
        if title is not None:
            flat = title.replace("\t", " ").replace("\n", " ").strip()
            entries.append(
                (flat, label_hit.group(1) if label_hit else ""))
        pos = hit.end()
    return entries


def compile_file_map(
    root: str,
    assembly: list[tuple[str, bool]],
    macro_files: set[str],
    def_counts: dict[str, int],
    swallow: frozenset[str],
    stamp: str,
) -> None:
    lines = [
        f"<!-- Machine view. Generated by compile.py at {stamp} from",
        "     paper.tex (\\input order) + a content scan of every",
        "     .tex file (roles classified by content, not name).",
        "     REGENERATE: python3 scripts/compile.py file_map. The",
        "     .tex sources are authoritative. -->",
        "",
        "# File map (assembly order)",
        "",
        "| # | File | Role | In paper.tex | Inside |",
        "|---|---|---|---|---|",
    ]
    for i, (path, mentioned) in enumerate(assembly, 1):
        if path in macro_files:
            role, inside = "macros", "%d definitions" % def_counts[path]
        else:
            cells = [
                (f"{title} ({label})" if label else title)
                .replace("|", "\\|")
                for title, label in scan_headings(
                    os.path.join(root, path), swallow)
            ]
            role, inside = "prose", ", ".join(cells) or "---"
        lines.append("| %d | %s | %s | %s | %s |" % (
            i,
            path,
            role,
            "\\input" if mentioned else "--- (not included yet)",
            inside,
        ))
    lines += [
        "",
        "## Scan limits",
        "",
        "- Roles are by content: a macro source holds definitions and",
        "  no prose sentences; anything else is prose (see",
        "  references/file_map.md).",
        "- Argument-swallowing macros (\\eat-style: a declared argument",
        "  the body never uses) are blanked before scanning -- eaten",
        "  content, eaten headings included, is not listed.",
        "- Heading titles are raw (macros unexpanded); a title reads to",
        "  its matching closing brace even across lines.",
        "- A heading's label is the first \\label before the next",
        "  heading; unlabeled headings print bare.",
        "",
    ]
    copilot.write_view(root, "file_map", lines)
